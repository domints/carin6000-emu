//============================================================
//  MACHINE CONFIG
//============================================================

void opel_dvd90_state::opel_dvd90(machine_config &config)
{
	// TLCS-900/H radio CPU
	TMP95C063(config, m_radiocpu, XTAL(8'000'000));
	m_radiocpu->set_addrmap(AS_PROGRAM, &opel_dvd90_state::radiocpu_map);

	// MIPS navigation CPU
	R4000BE(config, m_navcpu, XTAL(25'000'000));
	m_navcpu->set_addrmap(AS_PROGRAM, &opel_dvd90_state::navcpu_map);

	// Video screen
	screen_device &screen(SCREEN(config, "screen"));
	screen.set_refresh_hz(60);
	screen.set_vblank_time(ATTOSECONDS_IN_USEC(0));
	screen.set_size(320, 240);
	screen.set_visarea(0, 319, 0, 239);
	screen.set_screen_update(FUNC(opel_dvd90_state::screen_update));
}


